// Internal migration bookkeeping. Provider verification and authorization must
// happen in trusted server code before a receipt is passed to this module.
const safeID = value => typeof value === 'string' && value.length > 0 && value.length <= 512 && !/[\x00-\x1f\x7f]/.test(value);
const validHash = value => typeof value === 'string' && /^[a-f0-9]{64}$/.test(value);

export function createStorageMigration({ organizationId, source, destination, records, sourceSnapshotComplete, pendingUploads }) {
  if (!safeID(organizationId) || !safeID(source) || !safeID(destination) || source === destination || !Array.isArray(records) ||
      sourceSnapshotComplete !== true || pendingUploads !== 0) throw new Error('invalid-migration');
  const seen = new Set();
  const items = records.map(record => {
    if (!record || typeof record !== 'object' || record.organizationId !== organizationId || record.storageIdentity !== source ||
        !safeID(record.authorId) || !safeID(record.recordId) || !safeID(record.remoteItemId) || !safeID(record.folderId) ||
        record.state !== 'verified' || !Number.isSafeInteger(record.byteCount) || record.byteCount < 1 ||
        !validHash(record.sha256) || seen.has(record.recordId)) throw new Error('migration-source-not-ready');
    seen.add(record.recordId);
    return { recordId: record.recordId, authorId: record.authorId, sourceItemId: record.remoteItemId, sourceFolderId: record.folderId,
      byteCount: record.byteCount, sha256: record.sha256, targetItemId: null, targetFolderId: null };
  });
  return { version: 1, organizationId, source, destination, items, sourceSnapshotComplete: true };
}

/** A receipt must be generated by the provider verifier, never by a mobile client. */
export function applyVerifiedMigrationReceipt(migration, receipt) {
  if (!migration || !Array.isArray(migration.items) || !receipt || typeof receipt !== 'object' ||
      migration.items.some(item => !item || typeof item !== 'object')) throw new Error('invalid-migration-receipt');
  const index = migration.items.findIndex(item => item.recordId === receipt.recordId);
  if (index < 0 || !safeID(receipt.targetItemId) || !safeID(receipt.targetFolderId)) throw new Error('invalid-migration-receipt');
  const previous = migration.items[index];
  if (receipt.byteCount !== previous.byteCount || receipt.sha256 !== previous.sha256 ||
      migration.items.some((item, i) => i !== index && item.targetItemId === receipt.targetItemId) ||
      (previous.targetItemId && (previous.targetItemId !== receipt.targetItemId || previous.targetFolderId !== receipt.targetFolderId))) {
    throw new Error('migration-receipt-mismatch');
  }
  const items = migration.items.slice();
  items[index] = { ...previous, targetItemId: receipt.targetItemId, targetFolderId: receipt.targetFolderId };
  return { ...migration, items };
}

// The final snapshot must be obtained by trusted server code after writes have
// stopped, and switching must occur in the same protected transaction/lease.
export function canSwitchStorage(migration, { organizationId, currentSource, currentDestination, permissionsVerified, writesQuiesced,
  finalRecords, finalSnapshotComplete, pendingUploads }) {
  if (!Array.isArray(finalRecords) || finalSnapshotComplete !== true || pendingUploads !== 0 || !Array.isArray(migration?.items) ||
      finalRecords.length !== migration.items.length) return false;
  const finalById = new Map();
  for (const record of finalRecords) {
    if (!record || record.organizationId !== organizationId || record.storageIdentity !== currentSource ||
        record.state !== 'verified' || !safeID(record.recordId) || finalById.has(record.recordId)) return false;
    finalById.set(record.recordId, record);
  }
  return migration?.version === 1 && safeID(organizationId) && organizationId === migration.organizationId &&
    safeID(migration.source) && safeID(migration.destination) && migration.source !== migration.destination &&
    migration.sourceSnapshotComplete === true && currentSource === migration.source && currentDestination === migration.destination &&
    permissionsVerified === true && writesQuiesced === true && Array.isArray(migration.items) &&
    migration.items.every(item => item && typeof item === 'object') &&
    new Set(migration.items.map(item => item.recordId)).size === migration.items.length &&
    new Set(migration.items.map(item => item.targetItemId)).size === migration.items.length &&
    migration.items.every(item => {
      const current = finalById.get(item.recordId);
      return safeID(item.recordId) && safeID(item.authorId) && safeID(item.sourceItemId) && safeID(item.sourceFolderId) &&
        safeID(item.targetItemId) && safeID(item.targetFolderId) && validHash(item.sha256) && Number.isSafeInteger(item.byteCount) && item.byteCount > 0 &&
        current?.authorId === item.authorId && current.remoteItemId === item.sourceItemId && current.folderId === item.sourceFolderId &&
        current.byteCount === item.byteCount && current.sha256 === item.sha256;
    });
}
